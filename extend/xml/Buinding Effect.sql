INSERT OR IGNORE INTO Building_BuildingClassYieldChanges
        (BuildingType, BuildingClassType, YieldType, YieldChange)
SELECT 'BUILDING_REGISTAN', BuildingClass, 'YIELD_FAITH', 4
FROM Buildings WHERE FaithCost > 0 AND Cost < 0
UNION ALL
SELECT 'BUILDING_REGISTAN', BuildingClass, 'YIELD_CULTURE', 4
FROM Buildings WHERE FaithCost > 0 AND Cost < 0;

DROP TRIGGER IF EXISTS REGISTAN_BuildingClassYieldChanges;
DROP TRIGGER IF EXISTS REGISTAN_BuildingClassYieldChanges2;

CREATE TRIGGER REGISTAN_BuildingClassYieldChanges
AFTER INSERT ON Buildings
WHEN NEW.FaithCost > 0 AND NEW.Cost < 0
BEGIN
    INSERT OR IGNORE INTO Building_BuildingClassYieldChanges
            (BuildingType, BuildingClassType, YieldType, YieldChange)
    VALUES  ('BUILDING_REGISTAN', NEW.BuildingClass, 'YIELD_FAITH',   4),
            ('BUILDING_REGISTAN', NEW.BuildingClass, 'YIELD_CULTURE', 4);
END;


